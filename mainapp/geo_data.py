def seed_geo(country_model, city_model):
    """Идемпотентно создаёт страны и города. Возвращает (новых стран, новых городов)."""
    new_countries = new_cities = 0
    for name, code, cities in COUNTRIES:
        country, created = country_model.objects.get_or_create(name=name, defaults={'code': code})
        new_countries += created
        for city_name in cities:
            _, created = city_model.objects.get_or_create(country=country, name=city_name)
            new_cities += created
    return new_countries, new_cities
